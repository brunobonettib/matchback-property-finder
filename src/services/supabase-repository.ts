import type { SupabaseClient } from "@supabase/supabase-js";
import { z } from "zod";
import type { Imovel, Interessado } from "@/domain/types";
import type { Repositorio } from "./repository";

const money = z
  .union([z.number(), z.string().min(1)])
  .pipe(z.coerce.number().finite().nonnegative());
const finalidade = z.enum(["compra", "aluguel"]);
const imovelFields = {
  titulo: z.string().trim().min(1),
  bairro: z.string().trim().min(1),
  finalidade,
  preco: money.refine((value) => value > 0),
  quartos: z.number().int().nonnegative(),
  status: z.enum(["disponivel", "reservado", "vendido", "alugado"]),
  demo: z.boolean().default(false),
};
const imovelSchema = z.object({ id: z.string().min(1), ...imovelFields });
const interessadoSchema = z.object({
  id: z.string().min(1),
  nome: z.string().min(1),
  finalidade,
  bairro_preferido: z.string().min(1),
  orcamento_maximo: money,
  quartos_minimos: z.number().int().nonnegative(),
  ultimo_contato: z.string().date(),
  contato: z.string().nullable(),
  demo: z.boolean(),
});
const imovelColumns = "id,titulo,bairro,finalidade,preco,quartos,status,demo";
const interessadoColumns =
  "id,nome,finalidade,bairro_preferido,orcamento_maximo,quartos_minimos,ultimo_contato,contato,demo";

export function mapImovel(row: unknown): Imovel {
  return imovelSchema.parse(row);
}

export function mapInteressado(row: unknown): Interessado {
  const r = interessadoSchema.parse(row);
  return {
    id: r.id,
    nome: r.nome,
    finalidade: r.finalidade,
    bairroPreferido: r.bairro_preferido,
    orcamentoMaximo: r.orcamento_maximo,
    quartosMinimos: r.quartos_minimos,
    ultimoContato: r.ultimo_contato,
    ...(r.contato === null ? {} : { contato: r.contato }),
    demo: r.demo,
  };
}

export function createSupabaseRepository(client: SupabaseClient, ownerId: string): Repositorio {
  async function requireOwner() {
    const { data, error } = await client.auth.getUser();
    if (error || !data.user || data.user.id !== ownerId) {
      throw new Error("Sessão inválida. Entre novamente para continuar.");
    }
  }
  return {
    async listarImoveis() {
      await requireOwner();
      const { data, error } = await client
        .from("imoveis")
        .select(imovelColumns)
        .eq("owner_id", ownerId)
        .order("id");
      if (error) throw new Error("Não foi possível carregar os imóveis.");
      return z.array(z.unknown()).parse(data).map(mapImovel);
    },
    async listarInteressados() {
      await requireOwner();
      const { data, error } = await client
        .from("interessados")
        .select(interessadoColumns)
        .eq("owner_id", ownerId)
        .order("id");
      if (error) throw new Error("Não foi possível carregar os interessados.");
      return z.array(z.unknown()).parse(data).map(mapInteressado);
    },
    async criarImovel(dados) {
      const values = z.object(imovelFields).parse(dados);
      await requireOwner();
      // owner_id comes from the verified session; id is generated by Postgres.
      const { data, error } = await client
        .from("imoveis")
        .insert({ ...values, owner_id: ownerId })
        .select(imovelColumns)
        .single();
      if (error)
        throw new Error(
          "Não foi possível confirmar a gravação. Confira o catálogo antes de tentar novamente.",
        );
      return mapImovel(data);
    },
  };
}
